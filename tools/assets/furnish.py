def bookcase():
    import random
    rnd = random.Random(3)
    w, d, h, t = 0.8, 0.35, 1.8, 0.02
    for sx in (-1, 1):
        box((t, d, h), (sx * (w / 2 - t / 2), 0, h / 2), OAK(), 0.002)
    box((w - 2 * t, 0.008, h - 0.04), (0, d / 2 - 0.004, h / 2), OAK(), 0.001)
    levels = [0.03, 0.4, 0.76, 1.12, 1.46, h - t / 2]
    for z in levels:
        box((w - 2 * t, d - 0.01, t), (0, -0.005, z), OAK(), 0.002)
    palette = [(0.55, 0.12, 0.1), (0.1, 0.2, 0.35), (0.15, 0.3, 0.2), (0.75, 0.68, 0.55), (0.2, 0.2, 0.22), (0.6, 0.45, 0.2), (0.85, 0.85, 0.82)]
    for li in range(len(levels) - 1):
        z0, x = levels[li] + t / 2, -w / 2 + t + 0.01
        limit = w / 2 - t - (0.13 if li % 2 else 0.02)
        while True:
            bw, bh = rnd.uniform(0.018, 0.045), rnd.uniform(0.2, 0.3)
            if x + bw > limit:
                break
            c = rnd.randrange(len(palette))
            box((bw, rnd.uniform(0.16, 0.24), bh), (x + bw / 2, -0.03, z0 + bh / 2), mat(f'book{c}', palette[c], 0.7), 0.002)
            x += bw + 0.002
        if li % 2:   # a small stack lying flat
            for k in range(3):
                box((0.11, 0.17, 0.025), (w / 2 - t - 0.07, -0.03, z0 + 0.0125 + k * 0.026), mat(f'book{k + 2}', palette[k + 2], 0.7), 0.002)


def trash_bin():
    r, h = 0.15, 0.45
    bpy.ops.mesh.primitive_cylinder_add(radius=r, depth=h, location=(0, 0, h / 2), vertices=48)
    o = bpy.context.object
    bm = bmesh.new(); bm.from_mesh(o.data)
    bmesh.ops.delete(bm, geom=[f for f in bm.faces if f.normal.z > 0.9], context='FACES')   # open top
    for v in bm.verts:
        if v.co.z < 0:
            v.co.x *= 0.88; v.co.y *= 0.88   # tapered
    bm.to_mesh(o.data); bm.free()
    o.modifiers.new('solid', 'SOLIDIFY').thickness = 0.004
    _finish(o, BLACK_STEEL())
    cyl(r * 0.86, 0.01, (0, 0, 0.005), BLACK_PLASTIC(), verts=48)


