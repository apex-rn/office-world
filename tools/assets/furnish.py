def keyboard(w=0.44, d=0.13, h=0.03):
    """Low-profile aluminium keyboard with real key caps."""
    box((w, d, 0.011), (0, 0, 0.0055), ALU(), 0.003)
    box((w - 0.004, d - 0.004, 0.002), (0, 0, 0.012), mat('key_well', (0.12, 0.12, 0.13), 0.6))
    key = mat('key_cap', (0.9, 0.9, 0.9), 0.5)
    bm = bmesh.new()
    u, gap, cols, rows = 0.0175, 0.0015, 0, 6
    x0, y0 = -w / 2 + 0.012, -d / 2 + 0.012
    widths = [[1] * 14, [1.5] + [1] * 12 + [1.5], [1.75] + [1] * 11 + [2.25], [2.25] + [1] * 10 + [2.75],
              [1.25] * 3 + [6.25] + [1.25] * 4, [1] * 14]
    for r, row in enumerate(reversed(widths)):
        x = x0
        for kw in row:
            if x + kw * u > w * 0.78 - 0.01:
                break
            sx = kw * u - gap
            bmesh.ops.create_cube(bm, size=1.0, matrix=__import__('mathutils').Matrix.LocRotScale(
                Vector((x + sx / 2, y0 + r * u + (u - gap) / 2, 0.0155)), None, Vector((sx, u - gap, 0.005))))
            x += kw * u
    px0 = -w / 2 + w * 0.78 + 0.006
    for c in range(4):           # numpad
        for r in range(5):
            bmesh.ops.create_cube(bm, size=1.0, matrix=__import__('mathutils').Matrix.LocRotScale(
                Vector((px0 + c * u + (u - gap) / 2, y0 + r * u + (u - gap) / 2, 0.0155)), None, Vector((u - gap, u - gap, 0.005))))
    me = bpy.data.meshes.new('keys'); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new('keys', me); bpy.context.collection.objects.link(o)
    o.location.x = 0
    bv = o.modifiers.new('bevel', 'BEVEL'); bv.width = 0.0012; bv.segments = 2
    _finish(o, key, uv=False)


