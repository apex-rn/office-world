def handle_bar(x, y, z, length, vertical=False):
    """Brushed steel bar handle on two stand-offs; y is the front face (Blender -Y points out)."""
    if vertical:
        cyl(0.006, length, (x, y - 0.025, z), STEEL(), verts=16)
        for s in (-1, 1):
            cyl(0.004, 0.025, (x, y - 0.0125, z + s * (length / 2 - 0.02)), STEEL(), rot=(math.pi / 2, 0, 0), verts=12)
    else:
        cyl(0.006, length, (x, y - 0.025, z), STEEL(), rot=(0, math.pi / 2, 0), verts=16)
        for s in (-1, 1):
            cyl(0.004, 0.025, (x + s * (length / 2 - 0.02), y - 0.0125, z), STEEL(), rot=(math.pi / 2, 0, 0), verts=12)


def text(body, loc, size, m, extrude=0.001, spacing=1.0, back=False):
    """Raised lettering facing -Y (front), or +Y (back=True: e.g. a desk's visitor side)."""
    bpy.ops.object.text_add(location=loc, rotation=(math.pi / 2, 0, math.pi if back else 0))
    t = bpy.context.object
    t.data.body = body; t.data.align_x = 'CENTER'; t.data.align_y = 'CENTER'
    t.data.size = size; t.data.extrude = extrude; t.data.space_character = spacing
    bpy.ops.object.convert(target='MESH')
    return _finish(t, m, uv=False)


def base_cabinet(w, d=0.6, h=0.9, doors=None):
    """Kitchen base unit: recessed plinth, white carcass, drawer row and doors with bar handles, marble top.
    The handles stand 31 mm proud of the fronts, so the fronts sit back by that much: the whole unit,
    handles included, stays inside the catalog's d."""
    plinth, tt, hd = 0.1, 0.03, 0.031
    fy = -d / 2 + hd                       # front face of doors and drawers
    box((w - 0.02, d - hd - 0.08, plinth), (0, (fy + d / 2) / 2 + 0.04, plinth / 2), BLACK_PLASTIC(), 0.002)
    ch = h - plinth - tt
    box((w, d / 2 - fy - 0.018, ch), (0, (fy + 0.018 + d / 2) / 2, plinth + ch / 2), WHITE_MATTE(), 0.002)
    n = doors or max(1, round(w / 0.6))
    dw, g = w / n, 0.003
    front = mat('front_matte', (0.80, 0.81, 0.79), 0.55)
    for i in range(n):
        x = -w / 2 + dw * (i + 0.5)
        box((dw - g, 0.018, 0.16 - g), (x, fy + 0.009, h - tt - 0.08), front, 0.002)          # drawer
        handle_bar(x, fy + 0.0005, h - tt - 0.08, min(0.32, dw * 0.55))
        dh = ch - 0.16
        box((dw - g, 0.018, dh - g), (x, fy + 0.009, plinth + dh / 2), front, 0.002)          # door
        handle_bar(x + (dw / 2 - 0.05) * (1 if i % 2 else -1), fy + 0.0005, plinth + dh - 0.1, 0.16, vertical=True)
    box((w, d - hd + 0.02, tt), (0, (fy - 0.02 + d / 2) / 2, h - tt / 2), MARBLE(), 0.003)   # top overhangs the fronts by 20 mm


