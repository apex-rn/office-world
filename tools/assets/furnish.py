    box((0.002, d * 0.42, 0.002), (0, -d * 0.2, h * 0.74), mat('seam', (0.0, 0.0, 0.0), 0.6))
    cyl(0.005, 0.008, (0, -d * 0.18, h * 0.72), mat('wheel', (0.2, 0.2, 0.21), 0.5), rot=(0, math.pi / 2, 0), verts=16)


