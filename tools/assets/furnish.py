    """Modern desk: white matte top on a black steel frame, cable tray, levelling feet."""
    top = 0.025
    box((w, d, top), (0, 0, h - top / 2), WHITE_MATTE(), 0.004)
    lx = w / 2 - 0.06
    for sx in (-1, 1):
        x = sx * lx
        for sy in (-1, 1):   # two posts per end frame
            box((0.05, 0.05, h - top - 0.03), (x, sy * (d / 2 - 0.07), (h - top - 0.03) / 2 + 0.03), BLACK_STEEL(), 0.004)
        box((0.05, d - 0.06, 0.05), (x, 0, 0.055), BLACK_STEEL(), 0.004)              # foot bar
        box((0.05, d - 0.1, 0.04), (x, 0, h - top - 0.02), BLACK_STEEL(), 0.004)       # top rail
