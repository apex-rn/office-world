"""Realistic office furniture built in Blender at the catalog's real dimensions, exported one GLB per catalog id.

blender -b --factory-startup -P furnish.py -- <materials_dir> <out_dir> <def id> [<def id> ...]

materials_dir is godot/assets/materials (Poly Haven CC0 sets: <name>/diff.jpg, nor.jpg, rough.jpg).
Convention (same as the catalog and office.gd): metres, footprint centred on the origin, standing on z=0,
front (the side a person uses) facing glTF +Z = Blender -Y. Each model fills exactly w x d x h from
packages/catalog/src/items.ts, so office.gd's uniform fit leaves it at scale 1. UV2 for lightmaps is
generated by Godot on import (furniture imports use "Static Lightmaps").
"""
import bpy, bmesh, math, os, sys
from mathutils import Vector

MATDIR, OUTDIR, *IDS = sys.argv[sys.argv.index('--') + 1:]

# ---------------------------------------------------------------- materials
_images, _mats = {}, {}


def _image(path, non_color=False, size=1024):
    """Load a texture at most `size` px wide. The glTF exporter copies the source file as is, so a downscaled
    copy is written to a temp folder and used instead (keeps each GLB small)."""
    if path not in _images:
        img = bpy.data.images.load(path)
        if img.size[0] > size:
            img.scale(size, size * img.size[1] // img.size[0])
            tmp = os.path.join(bpy.app.tempdir or '/tmp', f'{os.path.basename(os.path.dirname(path))}_{size}_{os.path.basename(path)}')
            img.filepath_raw = tmp; img.file_format = 'JPEG'; img.save()
        if non_color:
            img.colorspace_settings.name = 'Non-Color'
        _images[path] = img
    return _images[path]


def mat(name, color=(0.8, 0.8, 0.8), rough=0.5, metal=0.0, tex=None, tint=None, emit=None, alpha=None, relief_only=False):
    """Plain PBR, or a Poly Haven set (tex = folder name) optionally tinted; emit = (rgb, strength).
    relief_only: plain colour with only the set's normal map (the fabric set's colours read as tartan)."""
    key = (name, color, rough, metal, tex, tint, emit, alpha, relief_only)
    if key in _mats:
        return _mats[key]
    m = bpy.data.materials.new(name); m.use_nodes = True
    nt = m.node_tree; b = nt.nodes['Principled BSDF']
    b.inputs['Base Color'].default_value = (*color, 1)
    b.inputs['Roughness'].default_value = rough
    b.inputs['Metallic'].default_value = metal
    if tex:
        d = os.path.join(MATDIR, tex)
    if tex and not relief_only:
        col = nt.nodes.new('ShaderNodeTexImage'); col.image = _image(os.path.join(d, 'diff.jpg'))
        if tint:
            mix = nt.nodes.new('ShaderNodeMix'); mix.data_type = 'RGBA'; mix.blend_type = 'MULTIPLY'
            mix.inputs['Factor'].default_value = 1.0; mix.inputs['B'].default_value = (*tint, 1)
            nt.links.new(col.outputs['Color'], mix.inputs['A']); nt.links.new(mix.outputs['Result'], b.inputs['Base Color'])
        else:
            nt.links.new(col.outputs['Color'], b.inputs['Base Color'])
    if tex:
        nor = nt.nodes.new('ShaderNodeTexImage'); nor.image = _image(os.path.join(d, 'nor.jpg'), True, 512)
        nm = nt.nodes.new('ShaderNodeNormalMap'); nt.links.new(nor.outputs['Color'], nm.inputs['Color'])
        nt.links.new(nm.outputs['Normal'], b.inputs['Normal'])
        rf = os.path.join(d, 'rough.jpg')
        if os.path.exists(rf) and not relief_only:
            r = nt.nodes.new('ShaderNodeTexImage'); r.image = _image(rf, True, 256)
            nt.links.new(r.outputs['Color'], b.inputs['Roughness'])
    if emit:
        b.inputs['Emission Color'].default_value = (*emit[0], 1); b.inputs['Emission Strength'].default_value = emit[1]
    if alpha is not None:
        b.inputs['Alpha'].default_value = alpha
        if hasattr(m, 'surface_render_method'): m.surface_render_method = 'BLENDED'
    _mats[key] = m
    return m


WHITE_MATTE = lambda: mat('white_matte', (0.86, 0.86, 0.84), 0.62)
BLACK_STEEL = lambda: mat('black_steel', (0.035, 0.035, 0.038), 0.42, 0.85)
BLACK_PLASTIC = lambda: mat('black_plastic', (0.025, 0.025, 0.028), 0.45)
ALU = lambda: mat('aluminium', (0.78, 0.79, 0.81), 0.3, 1.0)
STEEL = lambda: mat('brushed_steel', (0.62, 0.63, 0.64), 0.28, 1.0)
GLASS_SCREEN = lambda: mat('screen', (0.02, 0.025, 0.03), 0.08, emit=((0.30, 0.42, 0.62), 1.6))

# ---------------------------------------------------------------- geometry helpers
parts = []


def _finish(o, m, bevel=0.0, segs=3, uv=True):
    o.data.materials.append(m)
    if bevel:
        bv = o.modifiers.new('bevel', 'BEVEL'); bv.width = bevel; bv.segments = segs; bv.limit_method = 'ANGLE'
        bv.harden_normals = True
    for p in o.data.polygons:
        p.use_smooth = True
    if uv and m.node_tree.nodes.get('Image Texture'):
        bpy.context.view_layer.objects.active = o
        bpy.ops.object.mode_set(mode='EDIT'); bpy.ops.mesh.select_all(action='SELECT')
        bpy.ops.uv.cube_project(cube_size=1.0, scale_to_bounds=False); bpy.ops.object.mode_set(mode='OBJECT')
    parts.append(o)
    return o


def box(size, center, m, bevel=0.0, segs=3, rot=(0, 0, 0)):
    """size (x, y, z) in metres, centre position; Blender axes (front = -Y)."""
    bpy.ops.mesh.primitive_cube_add(size=1, location=center, rotation=rot)
    o = bpy.context.object; o.scale = size
    bpy.ops.object.transform_apply(scale=True)
    return _finish(o, m, bevel, segs)


def cyl(r, depth, center, m, rot=(0, 0, 0), verts=32, bevel=0.0):
    bpy.ops.mesh.primitive_cylinder_add(radius=r, depth=depth, location=center, rotation=rot, vertices=verts)
    return _finish(bpy.context.object, m, bevel, 2)


def sphere(radii, center, m, segs=32):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segs, ring_count=segs // 2, location=center)
    o = bpy.context.object; o.scale = radii
    bpy.ops.object.transform_apply(scale=True)
    return _finish(o, m)


